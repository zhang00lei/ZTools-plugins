'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const root = path.resolve(__dirname, '..');
const sources = ['soundData.js', 'audioEngine.js', 'timer.js', 'storage.js', 'controller.js'];
const body = sources.map(file => fs.readFileSync(path.join(root, 'js', file), 'utf8')
  .replace(/^export /gm, '')).join('\n\n');
const output = `/** Generated by npm run build from js/. Do not edit directly. */\n(function () {\n'use strict';\n${body}\n})();\n`;
new vm.Script(output, { filename: 'app.js' });
fs.writeFileSync(path.join(root, 'app.js'), output);
console.log('Built app.js from js/ sources.');
